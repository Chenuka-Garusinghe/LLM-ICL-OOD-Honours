"""Make thesis/references.bib APA-ready (biblatex-apa): protect acronyms and names in titles,
split title/subtitle at the colon, give arXiv preprints eprint fields and the arXiv DOI."""
import re, sys
src, dst = sys.argv[1], sys.argv[2]
s = open(src).read()

def field_span(entry, name):
    m = re.search(r"(?im)^(\s*" + name + r"\s*=\s*)\{", entry)
    if not m: return None
    i = m.end(); depth = 1
    while depth:
        depth += {"{": 1, "}": -1}.get(entry[i], 0); i += 1
    return m.start(), m.end(), i - 1          # start of line, start of value, end of value (the closing brace)

def split_top(text, sep):
    depth = 0
    for i, ch in enumerate(text):
        depth += {"{": 1, "}": -1}.get(ch, 0)
        if depth == 0 and text.startswith(sep, i):
            return text[:i], text[i + len(sep):]
    return text, None

def protect(text):
    out, depth, buf = [], 0, ""
    def flush(b):
        # outside braces: brace any hyphen/space-separated token with 2+ capitals or a letter-digit mix
        def fix(tok):
            core = re.sub(r"[^A-Za-z0-9.]", "", tok)
            if sum(c.isupper() for c in core) >= 2 or (re.search(r"[A-Za-z]", core) and re.search(r"\d", core) and re.search(r"[A-Z]", core)):
                m = re.match(r"^([^A-Za-z0-9]*)(.*?)([^A-Za-z0-9.]*)$", tok)
                return f"{m.group(1)}{{{m.group(2)}}}{m.group(3)}"
            return tok
        return re.sub(r"[^\s\-]+", lambda m: fix(m.group(0)), b)
    for ch in text:
        if ch == "{":
            if depth == 0: out.append(flush(buf)); buf = ""
            depth += 1; buf += ch
        elif ch == "}":
            depth -= 1; buf += ch
            if depth == 0: out.append(buf); buf = ""
        else:
            buf += ch
    out.append(flush(buf) if depth == 0 else buf)
    return "".join(out)

def fix_entry(e):
    sp = field_span(e, "title")
    if sp:
        a, b, c = sp
        title = e[b:c]
        main, sub = split_top(title, ": ")
        main = protect(main.strip())
        rep = main + "}"
        if sub:
            rep += ",\n  subtitle  = {" + protect(sub.strip()) + "}"
        e = e[:b] + rep + e[c + 1:]
    if re.search(r"(?i)archivePrefix\s*=\s*\{arXiv\}", e):
        ep = re.search(r"(?i)eprint\s*=\s*\{([^}]*)\}", e).group(1)
        e = re.sub(r"(?im)^\s*howpublished\s*=\s*\{[^}]*\},?\n", "", e)
        e = re.sub(r"(?i)archivePrefix(\s*)=", r"eprinttype\1=", e)
        if not re.search(r"(?im)^\s*doi\s*=", e):
            i = e.index("{") + 1; depth = 1
            while depth:
                depth += {"{": 1, "}": -1}.get(e[i], 0); i += 1
            body = e[:i - 1].rstrip().rstrip(",")
            if e.lstrip().lower().startswith("@misc") and not re.search(r"(?im)^\s*publisher\s*=", body):
                body += ",\n  organization  = {arXiv}"
            e = body + f",\n  doi           = {{10.48550/arXiv.{ep}}}\n}}" + e[i:]
    return e

parts = re.split(r"(?m)^(?=@)", s)
out = [parts[0]] + [fix_entry(p) for p in parts[1:]]
open(dst, "w").write("% GENERATED by tools/apa_bib.py from ../docs/references.bib -- do not edit here; edit the source and run `make bib`.\n" + "".join(out))
